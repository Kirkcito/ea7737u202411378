import {HttpClient, HttpErrorResponse} from '@angular/common/http';
import {catchError, map, Observable, throwError} from 'rxjs';
import {BaseResource} from './base-resource';
import {BaseAssembler} from './base-assembler';


export abstract class BaseApiEndpoint<TEntity, TResource extends BaseResource, TResponse,
  TAssembler extends BaseAssembler<TEntity, TResource, TResponse>> {

  protected constructor(protected http: HttpClient, protected endpointUrl: string, protected assembler: TAssembler) {
  }

  /** Gets all the entities of the endpoint. */
  getAll(): Observable<TEntity[]> {
    return this.http.get<TResponse>(this.endpointUrl).pipe(
      map(response => this.assembler.toEntitiesFromResponse(response)),
      catchError(this.handleError));
  }

  /** Creates an entity; the identifier is generated by the API. */
  create(entity: TEntity): Observable<TEntity> {
    const {id, ...resource} = this.assembler.toResourceFromEntity(entity);
    return this.http.post<TResource>(this.endpointUrl, resource).pipe(
      map(created => this.assembler.toEntityFromResource(created)),
      catchError(this.handleError));
  }

  private handleError(error: HttpErrorResponse): Observable<never> {
    return throwError(() => new Error(error.status === 0 ? 'errors.api-unavailable' : 'errors.request-failed'));
  }
}
